"""Repair migration: make sure the columns declared in rider_app's migration
state really exist in the database.

Background
----------
On 2025-05-15 (commit d834a54) ``rider_app/migrations/0001_initial.py`` was
rewritten in place to add ``OrderAssignment.response_time`` and
``OrderAssignment.acceptance_score``, and the follow-up migrations
(``0002_initial``, ``0002_add_acceptance_fields``,
``0003_remove_rider_acceptance_rate_and_more``, ``0004_rider_assigned_at``)
were deleted in the same commit. A database that had already been migrated
with the previous migration set kept the old table layout, while
``django_migrations`` still recorded ``rider_app.0001_initial`` as applied.
Django therefore reported "no migrations to apply" while the columns were
missing, and the application failed with::

    no such column: rider_app_orderassignment.response_time

raised from ``rider_app.views.rider_earnings`` (it selects every assignment
column) and from the ``pre_save`` handler in ``rider_app.signals``.

Design
------
* Introspection guarded: the live schema is inspected first and only the
  columns that are actually missing are added.  On a healthy database the
  migration executes no DDL at all.
* Idempotent: running it twice is harmless.
* Non destructive: it only ever adds columns. Existing rows and their values
  are preserved, and the reverse operation is a no-op so a rollback can never
  drop a column that holds production data.
* Backend agnostic: the DDL is generated by Django's schema editor, so the
  column types match the backend (``interval`` on PostgreSQL, ``bigint``
  microseconds on SQLite).
"""
from django.db import migrations

TABLE = 'rider_app_orderassignment'
REPAIRED_FIELDS = ('response_time', 'acceptance_score')


def existing_columns(connection):
    """Return the column names currently present on the assignments table."""
    with connection.cursor() as cursor:
        return {
            description.name
            for description in connection.introspection.get_table_description(
                cursor, TABLE
            )
        }


def ensure_acceptance_columns(apps, schema_editor):
    model = apps.get_model('rider_app', 'orderassignment')
    present = existing_columns(schema_editor.connection)
    for field_name in REPAIRED_FIELDS:
        if field_name in present:
            continue
        schema_editor.add_field(model, model._meta.get_field(field_name))


def noop(apps, schema_editor):
    """Reverse is deliberately a no-op: columns may hold production data."""


class Migration(migrations.Migration):

    dependencies = [
        ('rider_app', '0001_initial'),
    ]

    operations = [
        migrations.RunPython(
            ensure_acceptance_columns, noop, elidable=False
        ),
    ]
